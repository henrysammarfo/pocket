// Writes docs/TEST_REPORT.md from the last `npm run test:all` run (test-results/), plus a fresh smoke test
// of the hosted site. Usage: npm run report -- https://hosted-url   (or SMOKE_URL=...)
import { execSync, spawnSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
const url = process.argv[2] || process.env.SMOKE_URL || '';
const sh = (c) => { try { return execSync(c, { encoding: 'utf8' }).trim(); } catch { return ''; } };
const commit = sh('git rev-parse --short HEAD'), branch = sh('git rev-parse --abbrev-ref HEAD');
const R = 'test-results';
const read = (f) => (existsSync(`${R}/${f}`) ? readFileSync(`${R}/${f}`, 'utf8') : '');
const summary = read('summary.md');
const runAt = (summary.match(/# Test run (\S+)/) || [])[1] || 'no local run found';
const unit = (read('unit.log').match(/Tests\s+(\d+) passed/) || [])[1] || '?';
let pass = 0, fail = 0;
for (const f of existsSync(R) ? readdirSync(R).filter((f) => f.endsWith('.log')) : []) { const t = read(f); pass += (t.match(/^PASS /gm) || []).length; fail += (t.match(/^FAIL /gm) || []).length; }
const views = (read('responsive-matrix.log').match(/checked (\d+) page views, (\d+) with overflow/) || []);
const table = summary ? summary.slice(summary.indexOf('| Step'), summary.lastIndexOf('|') + 1) : '_Run `npm run test:all` first._';
let smoke = 'not run (pass a URL)';
let smokeLines = '';
if (url) { const r = spawnSync('node', ['tests/smoke.mjs', url], { encoding: 'utf8' }); smokeLines = (r.stdout || '').trim(); smoke = r.status === 0 ? `PASS (${(smokeLines.match(/^PASS /gm) || []).length} checks)` : `FAIL\n\n${smokeLines.split('\n').filter((l) => l.startsWith('FAIL')).join('\n')}`; }
const hosted = existsSync('docs/TEST_REPORT.hosted.md') ? readFileSync('docs/TEST_REPORT.hosted.md', 'utf8').trim() : '';
const shots = existsSync('docs/shots') ? readdirSync('docs/shots').filter((f) => f.endsWith('.png')).sort() : [];
const md = `# Test report

Generated by \`npm run report\` on ${new Date().toISOString().replace('T', ' ').slice(0, 16)} UTC, commit \`${commit}\` (${branch}).

## Local run, clean state (\`npm run test:all\`, ${runAt})
- Unit tests: **${unit} passed** (these also run on Vercel before every build; a failure blocks the deploy)
- Browser and smoke checks: **${pass} PASS, ${fail} FAIL**
- Responsive matrix: **${views[1] || '?'} page views, ${views[2] ?? '?'} with overflow**

${table}

## Hosted site${url ? ` (${url})` : ''}
- Smoke test now: **${smoke}**
${hosted ? '\n' + hosted + '\n' : ''}
${shots.length ? '## Screenshots of the hosted run\n' + shots.map((f) => `- [${f}](shots/${f})`).join('\n') + '\n' : ''}
How to reproduce: \`npm ci && npm run setup && npm run test:all && npm run report -- <your url>\`. Details in [TESTING.md](TESTING.md).
`;
writeFileSync('docs/TEST_REPORT.md', md); console.log(md);
